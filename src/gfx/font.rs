/// The largest index `index_of` can answer.
///
/// Published because the console packs an index into twelve bits, and a font
/// that grew past that would not fail: it would start drawing the wrong
/// letter in the wrong colour, everywhere, at once.
pub const MAX_INDEX: u16 = EXTRA_BASE + EXTRA.len() as u16 - 1;

/// The glyph index for a codepoint.
///
/// Called once per character *printed*. `rows` is called once per character
/// *painted*, which on a full console is nine thousand times a frame, so the
/// search lives here and the paint path is an array index. That is the whole
/// reason the console stores an index rather than a codepoint.
pub fn index_of(c: char) -> u16 {
    let cp = c as u32;
    if (FIRST as u32..=LAST as u32).contains(&cp) {
        return (cp - FIRST as u32) as u16;
    }
    // Sorted by codepoint, asserted at boot, so this is a binary search and
    // not a scan of two hundred entries.
    let mut lo = 0usize;
    let mut hi = EXTRA.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        if EXTRA[mid].0 < cp {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if lo < EXTRA.len() && EXTRA[lo].0 == cp {
        EXTRA_BASE + lo as u16
    } else {
        UNKNOWN
    }
}

/// Row bitmaps for a glyph index.
#[inline]
pub fn rows(idx: u16) -> &'static [u8; 8] {
    if idx < UNKNOWN {
        &GLYPHS[idx as usize]
    } else if idx == UNKNOWN {
        &REPLACEMENT
    } else {
        match EXTRA.get((idx - EXTRA_BASE) as usize) {
            Some((_, r)) => r,
            None => &REPLACEMENT,
        }
    }
}

/// How many glyphs this font draws.
pub fn count() -> usize {
    GLYPHS.len() + 1 + EXTRA.len()
}

/// The codepoint an extended glyph draws, for the coverage report.
pub fn extra_at(i: usize) -> Option<u32> {
    EXTRA.get(i).map(|(cp, _)| *cp)
}

pub fn extra_count() -> usize {
    EXTRA.len()
}

