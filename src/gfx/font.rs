//! An 8x8 bitmap font: printable ASCII by hand, and 229 glyphs above it.
//!
//! 8x8 rather than 8x16: it is half the data, it is the cell size Terry used,
//! and drawn at 2x scale it is more legible on a 1080p panel than an unscaled
//! 8x16 would be. At 2x on 1920x1080 the console is 120x67 characters.
//!
//! Bit convention: one byte per row, top row first, and **bit 7 (0x80) is the
//! leftmost pixel**. Glyphs are drawn on a 5-wide grid occupying bits 6..2, so
//! a full row is 0x7C and the character cell has natural side bearing. Box
//! drawing breaks that rule and fills all eight bits, because a line that
//! stops short of the cell edge does not join the line in the cell beside it.
//!
//! **The extended half is generated and the ASCII half is not.** Most of what
//! is above 0x7E is not a new drawing: an accented letter is a letter this
//! file already contains with a mark over it, and drawing it a second time by
//! hand would let the two versions drift until an 'e' and the 'e' inside an
//! 'é' stopped being the same shape. `tools/font.py` composes them, reading
//! the ASCII table out of this very file so there is one copy of every letter.
//! Run `--proof` and look at the result; a bitmap font is one of the few
//! things here where nothing but a person can say whether it is right.
//!
//! What it does not have, said plainly rather than found later: no CJK, which
//! needs a 16x16 cell and a table three orders of magnitude larger; no
//! combining marks, no shaping, no bidirectional text and no grapheme
//! clusters. One codepoint is one cell, so an 'e' followed by U+0301 draws as
//! two cells and not as an accented e. Anything with no glyph gets the hollow
//! box, deliberately: a font that quietly substituted something close would be
//! lying about what it can draw.

