/// Row bitmaps for `c`, falling back to a hollow box for anything unprintable.
#[inline]
pub fn glyph(c: u8) -> &'static [u8; 8] {
    if c < FIRST || c > LAST {
        return &REPLACEMENT;
    }
    &GLYPHS[(c - FIRST) as usize]
}
