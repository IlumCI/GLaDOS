    if total:
        print()
        print(f"[wlanprov] {total} fault(s) in {len(files)} file(s).")
        print("[wlanprov] Every file under src/wlan/ says where it came from,")
        print("[wlanprov] or says 'Written for GLaDOS.' Those are the two options.")
        return 1

